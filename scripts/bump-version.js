#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const pkgPath = path.join(rootDir, 'package.json');
const pkgLockPath = path.join(rootDir, 'package-lock.json');
const cargoPath = path.join(rootDir, 'src-tauri', 'Cargo.toml');
const versionTsPath = path.join(rootDir, 'src', 'renderer', 'src', 'version.ts');

const arg = process.argv[2] || 'patch';

const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
const currentVersion = pkg.version;
const [major, minor, patch] = currentVersion.split('.').map(Number);

let nextVersion = '';
if (arg === 'major') {
  nextVersion = `${major + 1}.0.0`;
} else if (arg === 'minor') {
  nextVersion = `${major}.${minor + 1}.0`;
} else if (arg === 'patch') {
  nextVersion = `${major}.${minor}.${patch + 1}`;
} else if (/^\d+\.\d+\.\d+$/.test(arg)) {
  nextVersion = arg;
} else {
  console.error(`Unknown bump type: ${arg}. Use major, minor, patch, or x.y.z`);
  process.exit(1);
}

console.log(`Bumping version: ${currentVersion} -> ${nextVersion}`);

// 1. package.json
pkg.version = nextVersion;
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');

// 2. package-lock.json
if (fs.existsSync(pkgLockPath)) {
  const pkgLock = JSON.parse(fs.readFileSync(pkgLockPath, 'utf8'));
  pkgLock.version = nextVersion;
  if (pkgLock.packages && pkgLock.packages['']) {
    pkgLock.packages[''].version = nextVersion;
  }
  fs.writeFileSync(pkgLockPath, JSON.stringify(pkgLock, null, 2) + '\n', 'utf8');
}

// 3. src-tauri/Cargo.toml
if (fs.existsSync(cargoPath)) {
  let cargoContent = fs.readFileSync(cargoPath, 'utf8');
  cargoContent = cargoContent.replace(/^version = ".*?"/m, `version = "${nextVersion}"`);
  fs.writeFileSync(cargoPath, cargoContent, 'utf8');
}

// 4. src/renderer/src/version.ts
const versionTsContent = `// Auto-generated by scripts/bump-version.js
export const APP_VERSION = '${nextVersion}';
export const APP_NAME = 'Omni Office';
export const APP_FULL_TITLE = 'Omni Office v${nextVersion} (2026)';
`;
fs.writeFileSync(versionTsPath, versionTsContent, 'utf8');

console.log(`Version successfully updated to ${nextVersion} across package.json, Cargo.toml, and version.ts`);
